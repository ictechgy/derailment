"""Inter-rater agreement between the author and a second labeler on the blind sample.

Usage:
    python benchmark/analyze_interrater.py --labels path/to/labels_v2_<tool id>.json

Reads the second labeler's export from labeling_tool_second.html, maps its ids back to the
author's labels through benchmark/second_labeler_key.json (round 2 labels and round 3 labels, with
their logged revisions applied), and writes benchmark/interrater_analysis.md: Cohen's kappa on
stance overall and per experiment group, the confusion table, agreement on the doubt channel and on
injection flags, and every disagreement. This is the first reliability evidence that is not
intra-rater (the author's round 1 vs round 2).
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parents[1]
BENCH = ROOT / "benchmark"
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(BENCH))

from analyze_human_labels import cohen_kappa, load_round2  # noqa: E402
from calibrate_stance_judge import doubt_of, load_heldout  # noqa: E402

from derailment.stance_judge import STANCES  # noqa: E402

KEY = BENCH / "second_labeler_key.json"
OUT = BENCH / "interrater_analysis.md"


def author_labels(key: list[dict]) -> dict[str, dict]:
    """The author's label for every sampled item, keyed by the sample's id."""
    round2 = load_round2()
    if round2 is None:
        sys.exit("error: benchmark/human_labels_v2.json is missing")
    _, round3 = load_heldout(BENCH / "labeling_items_controls.json", BENCH / "human_labels_controls.json")
    sets = {"round2": round2, "round3": round3}
    return {k["id"]: sets[k["set"]][k["original_id"]] for k in key}


def second_labels(path: pathlib.Path, key: list[dict]) -> dict[str, dict]:
    """The second labeler's export, checked to cover exactly the sample."""
    export = json.loads(path.read_text(encoding="utf-8"))
    if export.get("schema") != "derailment-labels/v2":
        sys.exit(f"error: {path} is not a derailment-labels/v2 export")
    labels = export["labels"]
    if set(labels) != {k["id"] for k in key}:
        sys.exit(f"error: {path} labels {len(labels)} items; the sample has {len(key)} — wrong tool or unfinished?")
    return labels


def kappa_rows(key: list[dict], author: dict, second: dict) -> list[str]:
    """Stance kappa and raw agreement, overall and per group."""
    groups = ["all", *sorted({k["group"] for k in key})]
    rows = ["| Group | n | κ | agreement |", "|---|---|---|---|"]
    for group in groups:
        ids = [k["id"] for k in key if group == "all" or k["group"] == group]
        a, b = {i: author[i]["stance"] for i in ids}, {i: second[i]["stance"] for i in ids}
        agree = sum(a[i] == b[i] for i in ids) / len(ids)
        rows.append(f"| {group} | {len(ids)} | {cohen_kappa(a, b, ids):.2f} | {agree:.2f} |")
    return rows


def confusion_rows(author: dict, second: dict) -> list[str]:
    """Rows: author; columns: second labeler."""
    rows = ["| author \\ second | " + " | ".join(STANCES) + " |", "|---" * (len(STANCES) + 1) + "|"]
    for stance in STANCES:
        counts = Counter(second[i]["stance"] for i in author if author[i]["stance"] == stance)
        rows.append(f"| {stance} | " + " | ".join(str(counts.get(s, 0)) for s in STANCES) + " |")
    return rows


def side_rows(author: dict, second: dict) -> list[str]:
    """Doubt-channel agreement where both say residual, and injection-flag kappa over all items."""
    both = [i for i in author if author[i]["stance"] == second[i]["stance"] == "residual"]
    doubt = sum(doubt_of(author[i]) == doubt_of(second[i]) for i in both)
    ids = list(author)
    inj_a = {i: str(bool(author[i].get("injection_detected"))) for i in ids}
    inj_b = {i: str(bool(second[i].get("injection_detected"))) for i in ids}
    return [f"- Doubt channel, where both labeled residual: {doubt}/{len(both)} agree",
            f"- Injection flag: κ {cohen_kappa(inj_a, inj_b, ids):.2f} "
            f"(author flagged {sum(v == 'True' for v in inj_a.values())}, second labeler {sum(v == 'True' for v in inj_b.values())})"]


def disagreement_rows(key: list[dict], author: dict, second: dict) -> list[str]:
    """Every item where the stances differ, with its origin for the author's review."""
    rows = ["| Sample id | origin | group | author | second |", "|---|---|---|---|---|"]
    for k in key:
        a, b = author[k["id"]]["stance"], second[k["id"]]["stance"]
        if a != b:
            rows.append(f"| {k['id']} | {k['set']} #{k['original_id']} | {k['group']} | {a} | {b} |")
    return rows


def build_report(key: list[dict], author: dict, second: dict, labels_name: str) -> str:
    """The whole markdown report."""
    lines = ["# Inter-rater Agreement", "", "> Generated by `benchmark/analyze_interrater.py` — do not edit by hand.", "",
             f"Author vs a second, non-author labeler (`{labels_name}`) on {len(key)} items drawn blind from the "
             "round 2 and round 3 sets (`build_second_labeler_set.py`), rubric v2.1.", "", "## Stance", ""]
    lines += kappa_rows(key, author, second) + ["", "## Confusion (rows: author, columns: second labeler)", ""]
    lines += confusion_rows(author, second) + ["", "## Doubt channel and injection", ""] + side_rows(author, second)
    lines += ["", "## Disagreements", ""] + disagreement_rows(key, author, second)
    return "\n".join(lines) + "\n"


def main() -> None:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--labels", type=pathlib.Path, required=True, help="the second labeler's export")
    args = parser.parse_args()
    key = json.loads(KEY.read_text(encoding="utf-8"))["items"]
    text = build_report(key, author_labels(key), second_labels(args.labels, key), args.labels.name)
    OUT.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
